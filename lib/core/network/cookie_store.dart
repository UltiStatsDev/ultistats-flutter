import 'package:dio/dio.dart';

/// Хранилище cookie для HTTP-клиента.
///
/// На мобильных и desktop-платформах cookie (включая httpOnly-сессию)
/// сохраняются между запусками приложения. На web cookie принадлежат браузеру,
/// поэтому там хранилище ничего не делает.
abstract class CookieStore {
  /// Подключает хранение cookie к [dio].
  void attach(Dio dio);

  /// Удаляет cookie сессии. Нужно при выходе и при протухшей сессии: сервер
  /// намеренно не очищает общую cookie, чтобы поздний ответ не разлогинил
  /// более новую сессию.
  Future<void> clear();
}
